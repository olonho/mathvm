use crate::ast::{AstNode, AstVisitor, BinaryOp, UnaryOp};
use crate::bytecode::{Bytecode, Instruction};
use crate::error::{Error, Result};
use crate::types::{Signature, VarType};
use std::collections::HashMap;

/// Translator trait for converting between different representations
pub trait Translator {
    /// Translate source code to an intermediate representation
    fn translate(&mut self, program: &AstNode) -> Result<()>;
}

/// Bytecode generator that converts AST to bytecode
pub struct BytecodeGenerator {
    bytecode: Bytecode,
    strings: HashMap<String, u16>,
    variables: HashMap<String, (u16, VarType)>, // (id, type)
    current_var_id: u16,
}

impl BytecodeGenerator {
    pub fn new() -> Self {
        BytecodeGenerator {
            bytecode: Bytecode::new(),
            strings: HashMap::new(),
            variables: HashMap::new(),
            current_var_id: 0,
        }
    }

    /// Get the generated bytecode
    pub fn get_bytecode(&self) -> &Bytecode {
        &self.bytecode
    }

    /// Take ownership of the generated bytecode
    pub fn take_bytecode(self) -> Bytecode {
        self.bytecode
    }

    /// Add a string constant and return its ID
    fn add_string_constant(&mut self, s: &str) -> u16 {
        if let Some(&id) = self.strings.get(s) {
            id
        } else {
            let id = self.strings.len() as u16;
            self.strings.insert(s.to_string(), id);
            id
        }
    }

    /// Get or create a variable ID
    fn get_or_create_variable(&mut self, name: &str, var_type: VarType) -> u16 {
        if let Some(&(id, _)) = self.variables.get(name) {
            id
        } else {
            let id = self.current_var_id;
            self.current_var_id += 1;
            self.variables.insert(name.to_string(), (id, var_type));
            id
        }
    }

    /// Get variable information
    fn get_variable(&self, name: &str) -> Option<(u16, VarType)> {
        self.variables.get(name).copied()
    }

    /// Generate optimized load instruction for small variable IDs
    fn generate_load_var(&mut self, var_id: u16, var_type: VarType) {
        match (var_type, var_id) {
            (VarType::Double, 0) => self.bytecode.add_instruction(Instruction::LoadDVar0),
            (VarType::Double, 1) => self.bytecode.add_instruction(Instruction::LoadDVar1),
            (VarType::Double, 2) => self.bytecode.add_instruction(Instruction::LoadDVar2),
            (VarType::Double, 3) => self.bytecode.add_instruction(Instruction::LoadDVar3),
            (VarType::Int, 0) => self.bytecode.add_instruction(Instruction::LoadIVar0),
            (VarType::Int, 1) => self.bytecode.add_instruction(Instruction::LoadIVar1),
            (VarType::Int, 2) => self.bytecode.add_instruction(Instruction::LoadIVar2),
            (VarType::Int, 3) => self.bytecode.add_instruction(Instruction::LoadIVar3),
            (VarType::String, 0) => self.bytecode.add_instruction(Instruction::LoadSVar0),
            (VarType::String, 1) => self.bytecode.add_instruction(Instruction::LoadSVar1),
            (VarType::String, 2) => self.bytecode.add_instruction(Instruction::LoadSVar2),
            (VarType::String, 3) => self.bytecode.add_instruction(Instruction::LoadSVar3),
            (VarType::Double, _) => {
                self.bytecode.add_instruction(Instruction::LoadDVar);
                self.bytecode.add_u16(var_id);
            }
            (VarType::Int, _) => {
                self.bytecode.add_instruction(Instruction::LoadIVar);
                self.bytecode.add_u16(var_id);
            }
            (VarType::String, _) => {
                self.bytecode.add_instruction(Instruction::LoadSVar);
                self.bytecode.add_u16(var_id);
            }
            _ => {
                // Fallback for unsupported types
                self.bytecode.add_instruction(Instruction::LoadIVar);
                self.bytecode.add_u16(var_id);
            }
        }
    }

    /// Generate optimized store instruction for small variable IDs
    fn generate_store_var(&mut self, var_id: u16, var_type: VarType) {
        match (var_type, var_id) {
            (VarType::Double, 0) => self.bytecode.add_instruction(Instruction::StoreDVar0),
            (VarType::Double, 1) => self.bytecode.add_instruction(Instruction::StoreDVar1),
            (VarType::Double, 2) => self.bytecode.add_instruction(Instruction::StoreDVar2),
            (VarType::Double, 3) => self.bytecode.add_instruction(Instruction::StoreDVar3),
            (VarType::Int, 0) => self.bytecode.add_instruction(Instruction::StoreIVar0),
            (VarType::Int, 1) => self.bytecode.add_instruction(Instruction::StoreIVar1),
            (VarType::Int, 2) => self.bytecode.add_instruction(Instruction::StoreIVar2),
            (VarType::Int, 3) => self.bytecode.add_instruction(Instruction::StoreIVar3),
            (VarType::String, 0) => self.bytecode.add_instruction(Instruction::StoreSVar0),
            (VarType::String, 1) => self.bytecode.add_instruction(Instruction::StoreSVar1),
            (VarType::String, 2) => self.bytecode.add_instruction(Instruction::StoreSVar2),
            (VarType::String, 3) => self.bytecode.add_instruction(Instruction::StoreSVar3),
            (VarType::Double, _) => {
                self.bytecode.add_instruction(Instruction::StoreDVar);
                self.bytecode.add_u16(var_id);
            }
            (VarType::Int, _) => {
                self.bytecode.add_instruction(Instruction::StoreIVar);
                self.bytecode.add_u16(var_id);
            }
            (VarType::String, _) => {
                self.bytecode.add_instruction(Instruction::StoreSVar);
                self.bytecode.add_u16(var_id);
            }
            _ => {
                // Fallback for unsupported types
                self.bytecode.add_instruction(Instruction::StoreIVar);
                self.bytecode.add_u16(var_id);
            }
        }
    }
}

impl Default for BytecodeGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl Translator for BytecodeGenerator {
    fn translate(&mut self, program: &AstNode) -> Result<()> {
        self.visit(program)?;
        self.bytecode.add_instruction(Instruction::Stop);
        Ok(())
    }
}

impl AstVisitor<Result<VarType>> for BytecodeGenerator {
    fn visit(&mut self, node: &AstNode) -> Result<VarType> {
        match node {
            AstNode::Program(statements) => self.visit_program(statements),
            AstNode::Block(statements) => self.visit_block(statements),
            AstNode::VarDeclaration {
                var_type,
                name,
                initializer,
            } => self.visit_var_declaration(*var_type, name, initializer),
            AstNode::FunctionDeclaration {
                name,
                signature,
                body,
            } => self.visit_function_declaration(name, signature, body),
            AstNode::NativeFunctionDeclaration {
                name,
                signature,
                native_name,
            } => self.visit_native_function_declaration(name, signature, native_name),
            AstNode::FunctionCall { name, arguments } => self.visit_function_call(name, arguments),
            AstNode::Print(arguments) => self.visit_print(arguments),
            AstNode::If {
                condition,
                then_branch,
                else_branch,
            } => self.visit_if(condition, then_branch, else_branch),
            AstNode::While { condition, body } => self.visit_while(condition, body),
            AstNode::For {
                variable,
                start,
                end,
                body,
            } => self.visit_for(variable, start, end, body),
            AstNode::Return(value) => self.visit_return(value),
            AstNode::Expression(expr) => self.visit_expression(expr),
            AstNode::BinaryOp { left, op, right } => self.visit_binary_op(left, op, right),
            AstNode::UnaryOp { op, operand } => self.visit_unary_op(op, operand),
            AstNode::Variable(name) => self.visit_variable(name),
            AstNode::IntLiteral(value) => self.visit_int_literal(*value),
            AstNode::DoubleLiteral(value) => self.visit_double_literal(*value),
            AstNode::StringLiteral(value) => self.visit_string_literal(value),
        }
    }

    fn visit_program(&mut self, statements: &[AstNode]) -> Result<VarType> {
        for statement in statements {
            self.visit(statement)?;
        }
        Ok(VarType::Void)
    }

    fn visit_block(&mut self, statements: &[AstNode]) -> Result<VarType> {
        let mut result_type = VarType::Void;
        for statement in statements {
            result_type = self.visit(statement)?;
        }
        Ok(result_type)
    }

    fn visit_var_declaration(
        &mut self,
        var_type: VarType,
        name: &str,
        initializer: &Option<Box<AstNode>>,
    ) -> Result<VarType> {
        let var_id = self.get_or_create_variable(name, var_type);

        if let Some(init) = initializer {
            let init_type = self.visit(init)?;

            // Generate type conversion if needed
            if init_type != var_type {
                match (init_type, var_type) {
                    (VarType::Int, VarType::Double) => {
                        self.bytecode.add_instruction(Instruction::I2D);
                    }
                    (VarType::Double, VarType::Int) => {
                        self.bytecode.add_instruction(Instruction::D2I);
                    }
                    (VarType::String, VarType::Int) => {
                        self.bytecode.add_instruction(Instruction::S2I);
                    }
                    _ => {
                        return Err(Error::type_error(&format!(
                            "Cannot convert {} to {}",
                            init_type.name(),
                            var_type.name()
                        )));
                    }
                }
            }

            self.generate_store_var(var_id, var_type);
        } else {
            // Initialize with default value
            match var_type {
                VarType::Int => self.bytecode.add_instruction(Instruction::ILoad0),
                VarType::Double => self.bytecode.add_instruction(Instruction::DLoad0),
                VarType::String => self.bytecode.add_instruction(Instruction::SLoad0),
                VarType::Void => return Err(Error::type_error("Cannot declare void variable")),
            }
            self.generate_store_var(var_id, var_type);
        }

        Ok(VarType::Void)
    }

    fn visit_function_declaration(
        &mut self,
        _name: &str,
        _signature: &Signature,
        _body: &AstNode,
    ) -> Result<VarType> {
        // TODO: Implement function declarations
        Err(Error::runtime_error(
            "Function declarations not yet implemented",
        ))
    }

    fn visit_native_function_declaration(
        &mut self,
        _name: &str,
        _signature: &Signature,
        _native_name: &str,
    ) -> Result<VarType> {
        // TODO: Implement native function declarations
        Err(Error::runtime_error(
            "Native function declarations not yet implemented",
        ))
    }

    fn visit_function_call(&mut self, _name: &str, _arguments: &[AstNode]) -> Result<VarType> {
        // TODO: Implement function calls
        Err(Error::runtime_error("Function calls not yet implemented"))
    }

    fn visit_print(&mut self, arguments: &[AstNode]) -> Result<VarType> {
        for arg in arguments {
            let arg_type = self.visit(arg)?;

            match arg_type {
                VarType::Int => self.bytecode.add_instruction(Instruction::IPrint),
                VarType::Double => self.bytecode.add_instruction(Instruction::DPrint),
                VarType::String => self.bytecode.add_instruction(Instruction::SPrint),
                VarType::Void => return Err(Error::type_error("Cannot print void value")),
            }
        }

        Ok(VarType::Void)
    }

    fn visit_if(
        &mut self,
        _condition: &AstNode,
        _then_branch: &AstNode,
        _else_branch: &Option<Box<AstNode>>,
    ) -> Result<VarType> {
        // TODO: Implement if statements with proper control flow
        Err(Error::runtime_error("If statements not yet implemented"))
    }

    fn visit_while(&mut self, _condition: &AstNode, _body: &AstNode) -> Result<VarType> {
        // TODO: Implement while loops with proper control flow
        Err(Error::runtime_error("While loops not yet implemented"))
    }

    fn visit_for(
        &mut self,
        _variable: &str,
        _start: &AstNode,
        _end: &AstNode,
        _body: &AstNode,
    ) -> Result<VarType> {
        // TODO: Implement for loops with proper control flow
        Err(Error::runtime_error("For loops not yet implemented"))
    }

    fn visit_return(&mut self, value: &Option<Box<AstNode>>) -> Result<VarType> {
        if let Some(val) = value {
            let return_type = self.visit(val)?;
            self.bytecode.add_instruction(Instruction::Return);
            Ok(return_type)
        } else {
            self.bytecode.add_instruction(Instruction::Return);
            Ok(VarType::Void)
        }
    }

    fn visit_expression(&mut self, expr: &AstNode) -> Result<VarType> {
        let expr_type = self.visit(expr)?;
        self.bytecode.add_instruction(Instruction::Pop);
        Ok(expr_type)
    }

    fn visit_binary_op(
        &mut self,
        left: &AstNode,
        op: &BinaryOp,
        right: &AstNode,
    ) -> Result<VarType> {
        match op {
            BinaryOp::Assign => {
                let right_type = self.visit(right)?;

                if let AstNode::Variable(name) = left {
                    if let Some((var_id, var_type)) = self.get_variable(name) {
                        // Generate type conversion if needed
                        if right_type != var_type {
                            match (right_type, var_type) {
                                (VarType::Int, VarType::Double) => {
                                    self.bytecode.add_instruction(Instruction::I2D);
                                }
                                (VarType::Double, VarType::Int) => {
                                    self.bytecode.add_instruction(Instruction::D2I);
                                }
                                (VarType::String, VarType::Int) => {
                                    self.bytecode.add_instruction(Instruction::S2I);
                                }
                                _ => {
                                    return Err(Error::type_error(&format!(
                                        "Cannot assign {} to {}",
                                        right_type.name(),
                                        var_type.name()
                                    )));
                                }
                            }
                        }

                        self.generate_store_var(var_id, var_type);
                        Ok(var_type)
                    } else {
                        Err(Error::UndefinedVariable(name.clone()))
                    }
                } else {
                    Err(Error::runtime_error("Invalid assignment target"))
                }
            }
            BinaryOp::AssignAdd => {
                if let AstNode::Variable(name) = left {
                    if let Some((var_id, var_type)) = self.get_variable(name) {
                        // Load current value
                        self.generate_load_var(var_id, var_type);

                        // Generate right operand
                        let right_type = self.visit(right)?;

                        // Generate addition
                        match (var_type, right_type) {
                            (VarType::Int, VarType::Int) => {
                                self.bytecode.add_instruction(Instruction::IAdd);
                            }
                            (VarType::Double, VarType::Double) => {
                                self.bytecode.add_instruction(Instruction::DAdd);
                            }
                            (VarType::Int, VarType::Double) => {
                                self.bytecode.add_instruction(Instruction::Swap);
                                self.bytecode.add_instruction(Instruction::I2D);
                                self.bytecode.add_instruction(Instruction::Swap);
                                self.bytecode.add_instruction(Instruction::DAdd);
                            }
                            (VarType::Double, VarType::Int) => {
                                self.bytecode.add_instruction(Instruction::I2D);
                                self.bytecode.add_instruction(Instruction::DAdd);
                            }
                            _ => {
                                return Err(Error::type_error("Invalid operands for addition"));
                            }
                        }

                        self.generate_store_var(var_id, var_type);
                        Ok(var_type)
                    } else {
                        Err(Error::UndefinedVariable(name.clone()))
                    }
                } else {
                    Err(Error::runtime_error("Invalid assignment target"))
                }
            }
            _ => {
                let left_type = self.visit(left)?;
                let right_type = self.visit(right)?;

                match op {
                    BinaryOp::Add => match (left_type, right_type) {
                        (VarType::Int, VarType::Int) => {
                            self.bytecode.add_instruction(Instruction::IAdd);
                            Ok(VarType::Int)
                        }
                        (VarType::Double, VarType::Double) => {
                            self.bytecode.add_instruction(Instruction::DAdd);
                            Ok(VarType::Double)
                        }
                        (VarType::Int, VarType::Double) => {
                            self.bytecode.add_instruction(Instruction::Swap);
                            self.bytecode.add_instruction(Instruction::I2D);
                            self.bytecode.add_instruction(Instruction::Swap);
                            self.bytecode.add_instruction(Instruction::DAdd);
                            Ok(VarType::Double)
                        }
                        (VarType::Double, VarType::Int) => {
                            self.bytecode.add_instruction(Instruction::I2D);
                            self.bytecode.add_instruction(Instruction::DAdd);
                            Ok(VarType::Double)
                        }
                        _ => Err(Error::type_error("Invalid operands for addition")),
                    },
                    BinaryOp::Subtract => match (left_type, right_type) {
                        (VarType::Int, VarType::Int) => {
                            self.bytecode.add_instruction(Instruction::ISub);
                            Ok(VarType::Int)
                        }
                        (VarType::Double, VarType::Double) => {
                            self.bytecode.add_instruction(Instruction::DSub);
                            Ok(VarType::Double)
                        }
                        (VarType::Int, VarType::Double) => {
                            self.bytecode.add_instruction(Instruction::Swap);
                            self.bytecode.add_instruction(Instruction::I2D);
                            self.bytecode.add_instruction(Instruction::Swap);
                            self.bytecode.add_instruction(Instruction::DSub);
                            Ok(VarType::Double)
                        }
                        (VarType::Double, VarType::Int) => {
                            self.bytecode.add_instruction(Instruction::I2D);
                            self.bytecode.add_instruction(Instruction::DSub);
                            Ok(VarType::Double)
                        }
                        _ => Err(Error::type_error("Invalid operands for subtraction")),
                    },
                    BinaryOp::Multiply => match (left_type, right_type) {
                        (VarType::Int, VarType::Int) => {
                            self.bytecode.add_instruction(Instruction::IMul);
                            Ok(VarType::Int)
                        }
                        (VarType::Double, VarType::Double) => {
                            self.bytecode.add_instruction(Instruction::DMul);
                            Ok(VarType::Double)
                        }
                        (VarType::Int, VarType::Double) => {
                            self.bytecode.add_instruction(Instruction::Swap);
                            self.bytecode.add_instruction(Instruction::I2D);
                            self.bytecode.add_instruction(Instruction::Swap);
                            self.bytecode.add_instruction(Instruction::DMul);
                            Ok(VarType::Double)
                        }
                        (VarType::Double, VarType::Int) => {
                            self.bytecode.add_instruction(Instruction::I2D);
                            self.bytecode.add_instruction(Instruction::DMul);
                            Ok(VarType::Double)
                        }
                        _ => Err(Error::type_error("Invalid operands for multiplication")),
                    },
                    BinaryOp::Divide => match (left_type, right_type) {
                        (VarType::Int, VarType::Int) => {
                            self.bytecode.add_instruction(Instruction::IDiv);
                            Ok(VarType::Int)
                        }
                        (VarType::Double, VarType::Double) => {
                            self.bytecode.add_instruction(Instruction::DDiv);
                            Ok(VarType::Double)
                        }
                        (VarType::Int, VarType::Double) => {
                            self.bytecode.add_instruction(Instruction::Swap);
                            self.bytecode.add_instruction(Instruction::I2D);
                            self.bytecode.add_instruction(Instruction::Swap);
                            self.bytecode.add_instruction(Instruction::DDiv);
                            Ok(VarType::Double)
                        }
                        (VarType::Double, VarType::Int) => {
                            self.bytecode.add_instruction(Instruction::I2D);
                            self.bytecode.add_instruction(Instruction::DDiv);
                            Ok(VarType::Double)
                        }
                        _ => Err(Error::type_error("Invalid operands for division")),
                    },
                    BinaryOp::Modulo => match (left_type, right_type) {
                        (VarType::Int, VarType::Int) => {
                            self.bytecode.add_instruction(Instruction::IMod);
                            Ok(VarType::Int)
                        }
                        _ => Err(Error::type_error("Modulo only supported for integers")),
                    },
                    BinaryOp::Equal => {
                        match (left_type, right_type) {
                            (VarType::Int, VarType::Int) => {
                                self.bytecode.add_instruction(Instruction::ICmp);
                                self.bytecode.add_instruction(Instruction::ILoad0);
                                self.bytecode.add_instruction(Instruction::Swap);
                                // TODO: Add conditional jump for equality
                                Ok(VarType::Int)
                            }
                            (VarType::Double, VarType::Double) => {
                                self.bytecode.add_instruction(Instruction::DCmp);
                                self.bytecode.add_instruction(Instruction::ILoad0);
                                self.bytecode.add_instruction(Instruction::Swap);
                                // TODO: Add conditional jump for equality
                                Ok(VarType::Int)
                            }
                            _ => Err(Error::type_error("Invalid operands for comparison")),
                        }
                    }
                    _ => Err(Error::runtime_error("Binary operation not yet implemented")),
                }
            }
        }
    }

    fn visit_unary_op(&mut self, op: &UnaryOp, operand: &AstNode) -> Result<VarType> {
        let operand_type = self.visit(operand)?;

        match op {
            UnaryOp::Minus => match operand_type {
                VarType::Int => {
                    self.bytecode.add_instruction(Instruction::INeg);
                    Ok(VarType::Int)
                }
                VarType::Double => {
                    self.bytecode.add_instruction(Instruction::DNeg);
                    Ok(VarType::Double)
                }
                _ => Err(Error::type_error("Invalid operand for unary minus")),
            },
            UnaryOp::Plus => match operand_type {
                VarType::Int | VarType::Double => Ok(operand_type),
                _ => Err(Error::type_error("Invalid operand for unary plus")),
            },
            UnaryOp::Not => {
                // TODO: Implement logical not
                Err(Error::runtime_error("Logical not not yet implemented"))
            }
        }
    }

    fn visit_variable(&mut self, name: &str) -> Result<VarType> {
        if let Some((var_id, var_type)) = self.get_variable(name) {
            self.generate_load_var(var_id, var_type);
            Ok(var_type)
        } else {
            Err(Error::UndefinedVariable(name.to_string()))
        }
    }

    fn visit_int_literal(&mut self, value: i64) -> Result<VarType> {
        match value {
            0 => self.bytecode.add_instruction(Instruction::ILoad0),
            1 => self.bytecode.add_instruction(Instruction::ILoad1),
            -1 => self.bytecode.add_instruction(Instruction::ILoadM1),
            _ => {
                self.bytecode.add_instruction(Instruction::ILoad);
                self.bytecode.add_i64(value);
            }
        }
        Ok(VarType::Int)
    }

    fn visit_double_literal(&mut self, value: f64) -> Result<VarType> {
        if value == 0.0 {
            self.bytecode.add_instruction(Instruction::DLoad0);
        } else if value == 1.0 {
            self.bytecode.add_instruction(Instruction::DLoad1);
        } else if value == -1.0 {
            self.bytecode.add_instruction(Instruction::DLoadM1);
        } else {
            self.bytecode.add_instruction(Instruction::DLoad);
            self.bytecode.add_f64(value);
        }
        Ok(VarType::Double)
    }

    fn visit_string_literal(&mut self, value: &str) -> Result<VarType> {
        if value.is_empty() {
            self.bytecode.add_instruction(Instruction::SLoad0);
        } else {
            let string_id = self.add_string_constant(value);
            self.bytecode.add_instruction(Instruction::SLoad);
            self.bytecode.add_u16(string_id);
        }
        Ok(VarType::String)
    }
}
